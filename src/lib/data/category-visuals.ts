/**
 * Returns the best representative icon, background color, text color, and border classes
 * for any AI category or subcategory.
 */
export function getCategoryVisuals(category: {
  slug?: string;
  id?: string;
  icon?: string;
  parentId?: string;
}): CategoryVisual {
  const slug = category.slug || "";
  const match = CATEGORY_VISUALS[slug];

  const base = match || DEFAULT_VISUAL;
  const icon = match?.icon || category.icon || base.icon;

  const containerClass = `${base.bgClass} ${base.borderClass} ${base.textClass} ${base.hoverBgClass} ${base.hoverBorderClass}`;

  return {
    ...base,
    icon,
    containerClass,
  };
}
